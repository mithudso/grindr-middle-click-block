#!/usr/bin/env node
// Regenerate docs/function-reference.md from the userscript.
//
// Generated rather than hand-written so the two cannot drift: if a function is
// missing from the doc it does not exist, and if it is there the same description
// sits above it in the source.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'Grindr Middle-Click Block.user.js');
const OUT = join(root, 'docs', 'function-reference.md');

const lines = readFileSync(SRC, 'utf8').split('\n');

const sections = [];
lines.forEach((l, i) => {
  const m = l.match(/^\s*\/\/\s*──\s*(.+?)\s*─+\s*$/);
  if (m) sections.push([i + 1, m[1]]);
});
const sectionFor = (ln) => {
  let cur = '(top level)';
  for (const [sl, name] of sections) { if (sl <= ln) cur = name; else break; }
  return cur;
};

const fns = [];
lines.forEach((l, i) => {
  const m = l.match(/^\s*(?:async\s+)?function\s+(\w+)\s*\(([^)]*)\)/);
  if (!m) return;
  const doc = [];
  for (let j = i - 1; j >= 0 && lines[j].trim().startsWith('//'); j -= 1) {
    const t = lines[j].trim().slice(2).trim();
    if (t && !/^[─\-═\s]+$/.test(t)) doc.unshift(t);
  }
  fns.push({ name: m[1], args: m[2], line: i + 1, doc: doc.join(' ') });
});

const buckets = new Map();
for (const f of fns) {
  const s = sectionFor(f.line);
  if (!buckets.has(s)) buckets.set(s, []);
  buckets.get(s).push(f);
}
const undocumented = fns.filter((f) => !f.doc);

const out = ['# Function reference', '',
  `Every named function in \`Grindr Middle-Click Block.user.js\` — **${fns.length}** of them —`,
  'grouped by the section of the file it lives in, with its signature, line number',
  'and what it does.', '',
  'Generated by `scripts/gen-function-reference.mjs`, so it stays honest: if a',
  'function is missing here it does not exist, and if it is here the description',
  'sits above it in the file too.', '',
  '| | |', '|---|---|',
  `| functions | ${fns.length} |`,
  `| documented | ${fns.length - undocumented.length} / ${fns.length} |`,
  `| sections | ${buckets.size} |`, ''];

for (const [sec, list] of [...buckets].sort((a, b) =>
  Math.min(...a[1].map((f) => f.line)) - Math.min(...b[1].map((f) => f.line)))) {
  out.push(`## ${sec}`, '', '| Function | Line | Description |', '|---|---|---|');
  for (const f of list.sort((a, b) => a.line - b.line)) {
    const args = f.args.length > 46 ? `${f.args.slice(0, 46)}…` : f.args;
    const desc = f.doc.replace(/\|/g, '\\|');
    out.push(`| \`${f.name}(${args})\` | ${f.line} | ${desc.length > 220 ? `${desc.slice(0, 217)}…` : desc} |`);
  }
  out.push('');
}

writeFileSync(OUT, out.join('\n'));
console.log(`docs/function-reference.md: ${fns.length} functions, ${undocumented.length} undocumented, ${buckets.size} sections`);
if (undocumented.length) {
  console.error('Undocumented functions:');
  for (const f of undocumented) console.error(`  ${f.line}\t${f.name}`);
  process.exitCode = 1;
}
